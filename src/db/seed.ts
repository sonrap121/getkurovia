async function seedDatabase(): Promise<void> {
  const [{ count }] = await db.select({ count: sql<number>`count(*)::int` }).from(categories);
  if (Number(count) > 0) return;

  await db.transaction(async (tx) => {
    const insertedCategories = await tx
      .insert(categories)
      .values(CATEGORY_SEED)
      .onConflictDoNothing()
      .returning({ id: categories.id, slug: categories.slug });

    const idBySlug = new Map(insertedCategories.map((row) => [row.slug, row.id]));

    const productRows: NewProduct[] = PRODUCT_SEED.map(({ category, ...rest }) => {
      const categoryId = idBySlug.get(category);
      if (!categoryId) throw new Error(`Unknown seed category: ${category}`);
      return { ...rest, categoryId };
    });

    await tx.insert(products).values(productRows).onConflictDoNothing();
  });
}

let seedPromise: Promise<void> | null = null;

/** Seeds the catalog on first use so a fresh database is never empty. Safe to call repeatedly. */
export function ensureSeeded(): Promise<void> {
  if (!seedPromise) {
    seedPromise = seedDatabase().catch((error) => {
      seedPromise = null;
      throw error;
    });
  }
  return seedPromise;
}
